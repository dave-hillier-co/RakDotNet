using RakDotNet.Interop.Tests.Harness;
using RakDotNet.Protocol.Wire;

namespace RakDotNet.Interop.Tests.Scenarios;

/// <summary>
/// RakNet's secure connection (LIBCAT_SECURITY), from Samples/Encryption/Encryption.cpp (a server with a generated key
/// pair, a client connecting with the known key or with two-way authentication, a message larger than the MTU, the
/// client's key read back on the server, and the failure packets PrintPacketHeader names) and
/// Samples/Tests/SecurityFunctionsTest.cpp (passwords, the ban list and the security exception list). Native peers are
/// interop-peer-secure. Keys are generated by the peer that uses them, so each implementation's keys meet the other's
/// handshake.
/// </summary>
[Collection(OneScenarioAtATime.Name)]
public sealed class SecurityScenarios
{
    private const byte UserPacket = ScenarioFlows.UserPacket;

    // A half-open connection lasts 10 s (RakPeer.cpp:5877-5881); a client whose request the server ignores fails then.
    private static readonly TimeSpan HandshakeTimeout = TimeSpan.FromSeconds(15);

    private static CancellationToken Token => TestContext.Current.CancellationToken;

    private static TimeSpan Timeout => InteropSession.DefaultTimeout;

    [Theory]
    [MemberData(nameof(PeerMatrix.ClientServer), MemberType = typeof(PeerMatrix))]
    public async Task A_client_with_the_servers_key_connects_and_every_datagram_after_the_handshake_is_encrypted(PeerKind client, PeerKind server)
    {
        var (session, serverKeys) = await StartSecureServerAsync(client, server);
        await using var owned = session;
        session.ConnectSecurity = ClientSecurityOptions.KnownKey(serverKeys.PublicKey);
        var (serverGuid, clientGuid) = await session.ConnectAsync(Token);

        // Encryption.cpp:96-101: the server sends a block larger than the MTU on ID_NEW_INCOMING_CONNECTION.
        var block = Marked(10_000);
        await session.Server.SendAsync(new SendOptions(clientGuid, block, Reliability.ReliableOrdered), Token);
        var message = Marked(300);
        await session.Client.SendAsync(new SendOptions(serverGuid, message, Reliability.ReliableOrdered), Token);

        Assert.Equal(block, (await session.ClientInbox.WaitForPacketAsync(p => p.MessageId == UserPacket, "the 10000-byte block", Timeout, Token)).Data.ToArray());
        Assert.Equal(message, (await session.ServerInbox.WaitForPacketAsync(p => p.MessageId == UserPacket, "the client's message", Timeout, Token)).Data.ToArray());
        // The marker the payloads repeat never crosses the proxy in the clear.
        Assert.DoesNotContain(session.Proxy.Datagrams, d => d.Payload.AsSpan().IndexOf(Marker) >= 0);
        Assert.Null(await session.Server.GetClientPublicKeyAsync(clientGuid, Token));
        // The block's split parts fill datagrams as native RakNet's do: on the 1492-byte MTU the reliability layer takes
        // OVERHEAD_BYTES off twice and Encrypt adds them back once (ReliabilityLayer.cpp:353-358, 3913-3920, 2304-2315),
        // which native peers send as 1445-byte datagrams.
        Assert.Equal(1445, session.Proxy.Datagrams.Where(d => d.Direction == ProxyDirection.BToA).Max(d => d.Payload.Length));

        await session.Client.CloseAsync(serverGuid, notify: true, Token);
        await session.ServerInbox.WaitForPacketAsync(p => p.MessageId == (byte)MessageId.DisconnectionNotification, "ID_DISCONNECTION_NOTIFICATION", Timeout, Token);
    }

    [Theory]
    [MemberData(nameof(PeerMatrix.ClientServer), MemberType = typeof(PeerMatrix))]
    public async Task Two_way_authentication_gives_the_server_the_clients_public_key(PeerKind client, PeerKind server)
    {
        // Encryption.cpp option 4: InitializeSecurity with bRequireClientKey, the client keys from GenerateServerKey, and
        // GetClientPublicKeyFromSystemAddress on the server.
        var (session, serverKeys) = await StartSecureServerAsync(client, server, requireClientKey: true);
        await using var owned = session;
        var clientKeys = await session.Client.GenerateKeysAsync(Token);
        session.ConnectSecurity = ClientSecurityOptions.TwoWay(serverKeys.PublicKey, clientKeys);

        var (serverGuid, clientGuid) = await session.ConnectAsync(Token);

        Assert.Equal(clientKeys.PublicKey, await session.Server.GetClientPublicKeyAsync(clientGuid, Token));
        var message = Marked(2_000);
        await session.Client.SendAsync(new SendOptions(serverGuid, message, Reliability.ReliableOrdered), Token);
        Assert.Equal(message, (await session.ServerInbox.WaitForPacketAsync(p => p.MessageId == UserPacket, "the client's message", Timeout, Token)).Data.ToArray());
    }

    [Theory]
    [MemberData(nameof(PeerMatrix.ClientServer), MemberType = typeof(PeerMatrix))]
    public async Task A_client_accepting_any_key_connects_securely(PeerKind client, PeerKind server)
    {
        var (session, serverKeys) = await StartSecureServerAsync(client, server);
        await using var owned = session;
        session.ConnectSecurity = ClientSecurityOptions.AcceptAnyPublicKey;

        var (serverGuid, _) = await session.ConnectAsync(Token);

        var message = Marked(100);
        await session.Client.SendAsync(new SendOptions(serverGuid, message, Reliability.Reliable), Token);
        Assert.Equal(message, (await session.ServerInbox.WaitForPacketAsync(p => p.MessageId == UserPacket, "the client's message", Timeout, Token)).Data.ToArray());
        Assert.DoesNotContain(session.Proxy.Datagrams, d => d.Payload.AsSpan().IndexOf(Marker) >= 0);
    }

    [Theory]
    [MemberData(nameof(PeerMatrix.ClientServer), MemberType = typeof(PeerMatrix))]
    public async Task A_wrong_server_key_is_reported_as_a_public_key_mismatch_until_the_attempts_run_out(PeerKind client, PeerKind server)
    {
        // Encryption.cpp PrintPacketHeader, ID_PUBLIC_KEY_MISMATCH: "Wrong public key passed to Connect()". The attempt stays
        // queued, so every reply reports it again (RakPeer.cpp:4788-4801).
        var (session, serverKeys) = await StartSecureServerAsync(client, server);
        await using var owned = session;
        var otherKey = (await session.Client.GenerateKeysAsync(Token)).PublicKey;

        await ConnectExpectingFailureAsync(session, ClientSecurityOptions.KnownKey(otherKey), MessageId.PublicKeyMismatch);
    }

    [Theory]
    [MemberData(nameof(PeerMatrix.ClientServer), MemberType = typeof(PeerMatrix))]
    public async Task An_insecure_client_is_told_of_a_public_key_mismatch_by_a_secure_server(PeerKind client, PeerKind server)
    {
        // With PKM_INSECURE_CONNECTION remote_public_key is never set (RakPeer.cpp:3197-3205), so a LIBCAT_SECURITY client
        // never matches a secure server's key.
        var (session, serverKeys) = await StartSecureServerAsync(client, server);
        await using var owned = session;

        await ConnectExpectingFailureAsync(session, security: null, MessageId.PublicKeyMismatch);
    }

    [Theory]
    [MemberData(nameof(PeerMatrix.ClientServer), MemberType = typeof(PeerMatrix))]
    public async Task A_secure_client_is_told_an_insecure_server_lacks_security(PeerKind client, PeerKind server)
    {
        // Encryption.cpp PrintPacketHeader, ID_OUR_SYSTEM_REQUIRES_SECURITY (RakPeer.cpp:4824-4838).
        await using var session = await InteropSession.StartSecureAsync(client, server, cancellationToken: Token);
        var key = (await session.Server.GenerateKeysAsync(Token)).PublicKey;

        await ConnectExpectingFailureAsync(session, ClientSecurityOptions.KnownKey(key), MessageId.OurSystemRequiresSecurity);
    }

    [Theory]
    [MemberData(nameof(PeerMatrix.ClientServer), MemberType = typeof(PeerMatrix))]
    public async Task A_server_requiring_client_keys_refuses_a_client_without_one(PeerKind client, PeerKind server)
    {
        // RakPeer.cpp:3503-3515: the server sends ID_REMOTE_SYSTEM_REQUIRES_PUBLIC_KEY over the new connection and closes it
        // silently. The ID is below ID_TIMESTAMP, so the connecting client drops it (RakPeer.cpp:6226-6241) and reports
        // ID_CONNECTION_ATTEMPT_FAILED when its half-open connection times out.
        var (session, serverKeys) = await StartSecureServerAsync(client, server, requireClientKey: true);
        await using var owned = session;

        Assert.Equal("CONNECTION_ATTEMPT_STARTED", await session.Client.ConnectAsync(
            new Harness.ConnectOptions(session.ProxyEndPoint, Security: ClientSecurityOptions.KnownKey(serverKeys.PublicKey)), Token));

        var failed = await session.ClientInbox.WaitForPacketAsync(
            p => p.MessageId is (byte)MessageId.ConnectionAttemptFailed or (byte)MessageId.ConnectionRequestAccepted, "ID_CONNECTION_ATTEMPT_FAILED", HandshakeTimeout, Token);
        Assert.Equal("ID_CONNECTION_ATTEMPT_FAILED", failed.MessageName);
        Assert.Empty(session.ClientInbox.Unconsumed);
        Assert.DoesNotContain(session.ServerInbox.Unconsumed, p => p.MessageId == (byte)MessageId.NewIncomingConnection);
        Assert.Equal("IS_NOT_CONNECTED", await session.Server.GetConnectionStateAsync(session.ClientStarted.PeerGuid, Token));
    }

    [Theory]
    [MemberData(nameof(PeerMatrix.ClientServer), MemberType = typeof(PeerMatrix))]
    public async Task Security_functions_test_passwords_and_bans_on_a_secure_server(PeerKind client, PeerKind server)
    {
        // SecurityFunctionsTest.cpp: the password checks and the ban list, with the server's security on, as the test's
        // disabled half does.
        var (session, serverKeys) = await StartSecureServerAsync(client, server);
        await using var owned = session;
        var password = "password"u8.ToArray();
        await session.Server.SetIncomingPasswordAsync(password, Token);
        Assert.Equal(password, await session.Server.GetIncomingPasswordAsync(Token));
        var known = ClientSecurityOptions.KnownKey(serverKeys.PublicKey);

        // No password, then a wrong one: ID_INVALID_PASSWORD over the secure connection (RakPeer.cpp:3519-3536).
        await ConnectRefusedAsync(session, new Harness.ConnectOptions(session.ProxyEndPoint, Security: known), MessageId.InvalidPassword);
        await ConnectRefusedAsync(session, new Harness.ConnectOptions(session.ProxyEndPoint, "badpass"u8.ToArray(), Security: known), MessageId.InvalidPassword);

        // The right one connects.
        var right = new Harness.ConnectOptions(session.ProxyEndPoint, password, Security: known);
        await ConnectAndCloseAsync(session, right);

        // Banned, then unbanned with RemoveFromBanList; banned again, then unbanned with ClearBanList.
        await session.Server.BanAsync("127.0.0.1", TimeSpan.Zero, Token);
        Assert.True(await session.Server.IsBannedAsync("127.0.0.1", Token));
        await ConnectRefusedAsync(session, right, MessageId.ConnectionBanned);
        await session.Server.UnbanAsync("127.0.0.1", Token);
        Assert.False(await session.Server.IsBannedAsync("127.0.0.1", Token));
        await ConnectAndCloseAsync(session, right);

        await session.Server.BanAsync("127.0.0.1", TimeSpan.Zero, Token);
        await ConnectRefusedAsync(session, right, MessageId.ConnectionBanned);
        await session.Server.ClearBansAsync(Token);
        Assert.False(await session.Server.IsBannedAsync("127.0.0.1", Token));
        await ConnectAndCloseAsync(session, right);
    }

    [Theory]
    [MemberData(nameof(PeerMatrix.ClientServer), MemberType = typeof(PeerMatrix))]
    public async Task The_security_exception_list_admits_a_listed_client_to_the_offline_handshake_only(PeerKind client, PeerKind server)
    {
        // SecurityFunctionsTest.cpp: AddToSecurityExceptionList, IsInSecurityExceptionList, RemoveFromSecurityExceptionList.
        // A listed address is answered without security (RakPeer.cpp:5211-5228), but a client that passed the key cannot
        // process an answer that is not there (RakPeer.cpp:4964-4992), so in RakNet 4.081 it never connects. The server
        // keeps the half-open connection; once the address is removed, a new client connects securely.
        var (session, serverKeys) = await StartSecureServerAsync(client, server);
        await using var owned = session;
        await session.Server.AddSecurityExceptionAsync("127.0.0.1", Token);
        Assert.True(await session.Server.IsInSecurityExceptionListAsync("127.0.0.1", Token));
        var known = ClientSecurityOptions.KnownKey(serverKeys.PublicKey);

        Assert.Equal("CONNECTION_ATTEMPT_STARTED", await session.Client.ConnectAsync(
            new Harness.ConnectOptions(session.ProxyEndPoint, Attempts: 3, AttemptIntervalMs: 100, Security: known), Token));
        await session.ClientInbox.WaitForPacketAsync(p => p.MessageId == (byte)MessageId.ConnectionAttemptFailed, "ID_CONNECTION_ATTEMPT_FAILED", Timeout, Token);
        Assert.Equal("IS_CONNECTING", await session.Server.GetConnectionStateAsync(session.ClientStarted.PeerGuid, Token));
        Assert.DoesNotContain(session.ClientInbox.Unconsumed, p => p.MessageId == (byte)MessageId.PublicKeyMismatch);

        await session.Server.RemoveSecurityExceptionAsync("127.0.0.1", Token);
        Assert.False(await session.Server.IsInSecurityExceptionListAsync("127.0.0.1", Token));
        session.ConnectSecurity = known;
        await session.ConnectAsync(await session.AddClientAsync(client, Token), Token);
    }

    [Theory]
    [MemberData(nameof(PeerMatrix.ClientServer), MemberType = typeof(PeerMatrix))]
    public async Task Encrypted_reliable_ordered_messages_survive_loss_reordering_and_duplication(PeerKind client, PeerKind server)
    {
        // Every datagram is authenticated and checked against the 1024-datagram replay window: duplicates are refused,
        // reordered ones within the window are accepted, and resends are new datagrams with new IVs.
        var (session, serverKeys) = await StartSecureServerAsync(client, server);
        await using var owned = session;
        session.ConnectSecurity = ClientSecurityOptions.KnownKey(serverKeys.PublicKey);
        var faults = new FaultOptions(Seed: 20261020, LossProbability: 0.05, DuplicationProbability: 0.1, Jitter: TimeSpan.FromMilliseconds(30));

        await ScenarioFlows.ReliableOrderedUnderLossAsync(session, faults, count: 120, messageSize: 400, Token);

        Assert.True(session.Proxy.Datagrams.Any(d => d.Fault.Duplicate), "The proxy duplicated nothing.");
    }

    private static readonly byte[] Marker = "RakDotNet secret"u8.ToArray();

    // A user message filled with the marker, so encryption can be checked on the wire.
    private static byte[] Marked(int length)
    {
        var data = new byte[length];
        data[0] = UserPacket;
        for (var i = 1; i < length; i++)
        {
            data[i] = Marker[(i - 1) % Marker.Length];
        }
        return data;
    }

    // A server with InitializeSecurity on, its key pair made by the server's own implementation.
    private static async Task<(InteropSession Session, SecurityKeys Keys)> StartSecureServerAsync(PeerKind client, PeerKind server, bool requireClientKey = false)
    {
        PeerMatrix.SkipUnlessSecureAvailable(client, server);
        await using var generator = await PeerMatrix.LaunchAsync(server, secure: true, Token);
        var keys = await generator.GenerateKeysAsync(Token);
        var session = await InteropSession.StartSecureAsync(
            client, server, serverOptions: new StartupOptions(Security: new ServerSecurityOptions(keys, requireClientKey)), cancellationToken: Token);
        return (session, keys);
    }

    // Connects with few, fast attempts and expects the reason repeated per reply, then ID_CONNECTION_ATTEMPT_FAILED.
    private static async Task ConnectExpectingFailureAsync(InteropSession session, ClientSecurityOptions? security, MessageId reason)
    {
        Assert.Equal("CONNECTION_ATTEMPT_STARTED", await session.Client.ConnectAsync(
            new Harness.ConnectOptions(session.ProxyEndPoint, Attempts: 2, AttemptIntervalMs: 100, Security: security), Token));

        var failed = await session.ClientInbox.WaitForPacketAsync(
            p => p.MessageId is (byte)MessageId.ConnectionAttemptFailed or (byte)MessageId.ConnectionRequestAccepted, "ID_CONNECTION_ATTEMPT_FAILED", Timeout, Token);
        Assert.Equal("ID_CONNECTION_ATTEMPT_FAILED", failed.MessageName);
        var reports = session.ClientInbox.Unconsumed;
        Assert.NotEmpty(reports);
        Assert.All(reports, p =>
        {
            Assert.Equal(MessageNames.Of((byte)reason), p.MessageName);
            Assert.Equal(new[] { (byte)reason }, p.Data.ToArray());
            Assert.Equal(session.ServerStarted.PeerGuid, p.PeerGuid);
        });
        Assert.DoesNotContain(session.ServerInbox.Unconsumed, p => p.MessageId == (byte)MessageId.NewIncomingConnection);
    }

    private static async Task ConnectRefusedAsync(InteropSession session, Harness.ConnectOptions options, MessageId reason)
    {
        Assert.Equal("CONNECTION_ATTEMPT_STARTED", await session.Client.ConnectAsync(options, Token));
        var refused = await session.ClientInbox.WaitForPacketAsync(
            p => p.MessageId is (byte)MessageId.InvalidPassword or (byte)MessageId.ConnectionBanned or (byte)MessageId.ConnectionRequestAccepted,
            MessageNames.Of((byte)reason), Timeout, Token);
        Assert.Equal(MessageNames.Of((byte)reason), refused.MessageName);
        // A refused connection must be gone on both sides before the next attempt (ConnectionStateMatchesOptions).
        await ScenarioFlows.WaitForStateAsync(session.Client, session.ServerStarted.PeerGuid, "IS_NOT_CONNECTED", Token);
        await ScenarioFlows.WaitForStateAsync(session.Server, session.ClientStarted.PeerGuid, "IS_NOT_CONNECTED", Token);
    }

    private static async Task ConnectAndCloseAsync(InteropSession session, Harness.ConnectOptions options)
    {
        Assert.Equal("CONNECTION_ATTEMPT_STARTED", await session.Client.ConnectAsync(options, Token));
        var accepted = await session.ClientInbox.WaitForPacketAsync(p => p.MessageId == (byte)MessageId.ConnectionRequestAccepted, "ID_CONNECTION_REQUEST_ACCEPTED", Timeout, Token);
        await session.ServerInbox.WaitForPacketAsync(p => p.MessageId == (byte)MessageId.NewIncomingConnection, "ID_NEW_INCOMING_CONNECTION", Timeout, Token);
        await session.Client.CloseAsync(accepted.PeerGuid, notify: true, Token);
        await session.ServerInbox.WaitForPacketAsync(p => p.MessageId == (byte)MessageId.DisconnectionNotification, "ID_DISCONNECTION_NOTIFICATION", Timeout, Token);
        await ScenarioFlows.WaitForStateAsync(session.Client, accepted.PeerGuid, "IS_NOT_CONNECTED", Token);
        await ScenarioFlows.WaitForStateAsync(session.Server, session.ClientStarted.PeerGuid, "IS_NOT_CONNECTED", Token);
    }
}
